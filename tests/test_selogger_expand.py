"""Tests for scripts/selogger_expand.py. Run: python3 -m unittest discover -s tests"""

import importlib.util
import io
import subprocess
import sys
import tempfile
import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
spec = importlib.util.spec_from_file_location('selogger_expand', ROOT / 'scripts' / 'selogger_expand.py')
expand = importlib.util.module_from_spec(spec)
sys.modules['selogger_expand'] = expand
spec.loader.exec_module(expand)

CHECKER = expand.find_checker(ROOT)


def write(path, text):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding='utf-8')


DOMAIN_TE = '''# Generated by selogger.

# Declarations
type foo_daemon, domain;
type foo_daemon_exec, exec_type, vendor_file_type, file_type;
init_daemon_domain(foo_daemon)

# Macros
get_prop(foo_daemon, vendor_foo_prop)

# Rules
allow foo_daemon foo_data_file:file { open read };
allow foo_daemon sysfs:file read;

# Withheld
# allow foo_daemon unlabeled:file read;
'''

FILE_CONTEXTS = '''# Collected denials
/data/vendor/foo(/.*)?\tu:object_r:foo_data_file:s0
/vendor/bin/foo-daemon\tu:object_r:foo_daemon_exec:s0
'''


class ExpandTest(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.addCleanup(self.tmp.cleanup)
        self.dump = Path(self.tmp.name) / 'dump'
        self.sepolicy = Path(self.tmp.name) / 'sepolicy'
        self.sepolicy.mkdir()
        write(self.dump / 'REVIEW.md', '# selogger review\n')
        write(self.dump / 'vendor' / 'foo_daemon.te', DOMAIN_TE)
        write(self.dump / 'vendor' / 'file_contexts', FILE_CONTEXTS)

    def run_expand(self, **kwargs):
        out = io.StringIO()
        report, touched = expand.expand(self.dump, self.sepolicy, out=out, **kwargs)
        return report, touched, out.getvalue()

    def check_style(self, *paths):
        if not CHECKER:
            self.skipTest('check_sepolicy.py is not in this tree')
        result = subprocess.run([sys.executable, str(CHECKER)] + [str(p) for p in paths],
                                capture_output=True, text=True)
        self.assertEqual(result.returncode, 0, result.stdout)

    def test_new_files_are_the_dump(self):
        report, touched, _ = self.run_expand()
        self.assertEqual((self.sepolicy / 'foo_daemon.te').read_text(), DOMAIN_TE)
        self.assertEqual((self.sepolicy / 'file_contexts').read_text(), FILE_CONTEXTS)
        self.assertEqual(len(report.created), 2)
        self.assertEqual(len(touched), 2)
        self.check_style(*touched)

    def test_second_run_changes_nothing(self):
        self.run_expand()
        report, touched, _ = self.run_expand()
        self.assertEqual(report.created + report.updated, [])
        self.assertEqual(len(report.unchanged), 2)
        self.assertEqual(report.skipped_types, [])
        self.assertEqual(touched, [])

    def test_entries_go_into_the_right_place_of_existing_contexts(self):
        write(self.sepolicy / 'file_contexts', '''# Devices
/dev/foo\tu:object_r:foo_device:s0

# Vendor
/vendor/bin/a\tu:object_r:a_exec:s0
/vendor/bin/z\tu:object_r:z_exec:s0
''')
        report, touched, _ = self.run_expand()
        text = (self.sepolicy / 'file_contexts').read_text()
        # The existing content is untouched and the section is where it sorts.
        self.assertIn('# Devices\n/dev/foo\tu:object_r:foo_device:s0\n\n# Vendor\n'
                      '/vendor/bin/a\tu:object_r:a_exec:s0\n/vendor/bin/z\tu:object_r:z_exec:s0\n', text)
        self.assertIn('# Collected denials\n/data/vendor/foo(/.*)?\tu:object_r:foo_data_file:s0\n'
                      '/vendor/bin/foo-daemon\tu:object_r:foo_daemon_exec:s0\n', text)
        self.assertLess(text.index('# Collected denials'), text.index('# Devices'))
        self.check_style(*touched)

    def test_existing_section_is_extended_in_order(self):
        write(self.sepolicy / 'file_contexts', '''# Collected denials
/vendor/bin/a\tu:object_r:a_exec:s0
/vendor/bin/z\tu:object_r:z_exec:s0
''')
        _, touched, _ = self.run_expand()
        lines = (self.sepolicy / 'file_contexts').read_text().splitlines()
        self.assertEqual([l.split('\t')[0] for l in lines[1:]],
                         ['/data/vendor/foo(/.*)?', '/vendor/bin/a', '/vendor/bin/foo-daemon', '/vendor/bin/z'])
        self.check_style(*touched)

    def test_conflicting_label_is_reported_and_kept(self):
        write(self.sepolicy / 'file_contexts',
              '/vendor/bin/foo-daemon\tu:object_r:other_exec:s0\n')
        report, _, _ = self.run_expand()
        text = (self.sepolicy / 'file_contexts').read_text()
        self.assertIn('other_exec', text)
        self.assertNotIn('foo_daemon_exec', text)
        self.assertEqual(len(report.conflicts), 1)

    def test_allow_permissions_are_extended_not_duplicated(self):
        write(self.sepolicy / 'foo_daemon.te', '''# Rules
allow foo_daemon foo_data_file:file read;
allow foo_daemon other:file read;
''')
        report, touched, _ = self.run_expand()
        text = (self.sepolicy / 'foo_daemon.te').read_text()
        self.assertIn('allow foo_daemon foo_data_file:file { open read };', text)
        self.assertEqual(text.count('foo_data_file:file'), 1)
        self.assertEqual(report.extended, 1)
        self.assertIn('allow foo_daemon other:file read;', text)
        self.check_style(*touched)

    def test_new_sections_keep_alphabetical_order(self):
        write(self.sepolicy / 'foo_daemon.te', '''# Macros
binder_use(foo_daemon)

# Withheld
# allow foo_daemon x:file read;
''')
        _, touched, _ = self.run_expand()
        text = (self.sepolicy / 'foo_daemon.te').read_text()
        order = [text.index('# ' + t) for t in ('Declarations', 'Macros', 'Rules', 'Withheld')]
        self.assertEqual(order, sorted(order))
        self.assertIn('binder_use(foo_daemon)\nget_prop(foo_daemon, vendor_foo_prop)\n', text)
        self.check_style(*touched)

    def test_unsorted_section_gets_a_new_block(self):
        write(self.sepolicy / 'foo_daemon.te', '''# Rules
allow foo_daemon z:file read;
allow foo_daemon a:file read;
''')
        self.run_expand()
        text = (self.sepolicy / 'foo_daemon.te').read_text()
        # What was there stays as it was.
        self.assertIn('# Rules\nallow foo_daemon z:file read;\nallow foo_daemon a:file read;\n\nallow foo_daemon foo_data_file',
                      text)

    def test_types_declared_elsewhere_are_not_declared_again(self):
        write(self.sepolicy / 'file.te', 'type foo_daemon_exec, exec_type, file_type;\n')
        report, touched, _ = self.run_expand()
        self.assertEqual(report.skipped_types, ['foo_daemon_exec'])
        text = (self.sepolicy / 'foo_daemon.te').read_text()
        self.assertNotIn('type foo_daemon_exec', text)
        self.assertIn('type foo_daemon, domain;', text)
        self.check_style(*touched)

    def test_platform_files_need_a_platform_dir(self):
        write(self.dump / 'platform' / 'priv.te', '# Generated by selogger.\n\n# Rules\nallow priv x:file read;\n')
        report, _, _ = self.run_expand()
        self.assertEqual(report.skipped_platform, ['platform/priv.te'])
        self.assertFalse((self.sepolicy / 'priv.te').exists())

        platform = Path(self.tmp.name) / 'platform'
        report, _, _ = self.run_expand(platform_dir=platform)
        self.assertTrue((platform / 'priv.te').exists())

    def test_dry_run_writes_nothing_and_shows_a_diff(self):
        report, touched, output = self.run_expand(dry_run=True)
        self.assertEqual(list(self.sepolicy.iterdir()), [])
        self.assertEqual(touched, [])
        self.assertIn('+allow foo_daemon sysfs:file read;', output)
        self.assertEqual(len(report.created), 2)

    def test_withheld_comments_are_carried_once(self):
        self.run_expand()
        self.run_expand()
        text = (self.sepolicy / 'foo_daemon.te').read_text()
        self.assertEqual(text.count('# allow foo_daemon unlabeled:file read;'), 1)

    def test_main_rejects_other_directories(self):
        stderr = io.StringIO()
        old = sys.stderr
        sys.stderr = stderr
        try:
            code = expand.main(['--dump', str(self.sepolicy), '--sepolicy-dir', str(self.sepolicy)])
        finally:
            sys.stderr = old
        self.assertEqual(code, 1)
        self.assertIn('not the output of', stderr.getvalue())


class StyleTest(unittest.TestCase):
    def test_file_contexts_order(self):
        entries = ['/vendor/bin/z', '/vendor/bin/hw/a', '/vendor', '/vendor/bin/a', '/Vendor/x(/.*)?']
        ordered = expand.sort_entries('file_contexts', [e + '\tu:x' for e in entries])
        # Directories before sibling files, parents before children.
        names = [e.split('\t')[0] for e in ordered]
        self.assertLess(names.index('/vendor/bin/hw/a'), names.index('/vendor/bin/a'))
        self.assertLess(names.index('/vendor'), names.index('/vendor/bin/hw/a'))

    def test_te_order_puts_macros_last(self):
        lines = ['get_prop(a, b)', 'allow z x:file read;', 'Allow a x:file read;', 'binder_use(a)']
        self.assertEqual(expand.sort_entries('x.te', lines),
                         ['Allow a x:file read;', 'allow z x:file read;', 'binder_use(a)', 'get_prop(a, b)'])

    def test_headings_follow_the_checker(self):
        self.assertEqual(expand.parse_heading('# Rules'), (1, 'Rules'))
        self.assertEqual(expand.parse_heading('## Sub section'), (2, 'Sub section'))
        self.assertIsNone(expand.parse_heading('# Generated by selogger.'))
        self.assertIsNone(expand.parse_heading('# allow a b:c d;'))


if __name__ == '__main__':
    unittest.main()
